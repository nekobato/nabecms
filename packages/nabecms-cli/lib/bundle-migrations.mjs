import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Resolve the runtime migration file locations for one host app.
 */
const resolveMigrationPaths = (projectRoot) => {
  const migrationsDir = path.join(projectRoot, "migrations");
  return {
    migrationsDir,
    journalPath: path.join(migrationsDir, "meta", "_journal.json"),
    outputPath: path.join(
      projectRoot,
      "src",
      "database",
      "runtime-migrations.generated.ts",
    ),
  };
};

/**
 * Read the drizzle journal and return ordered runtime migration entries.
 */
export const loadRuntimeMigrations = async ({
  projectRoot = process.cwd(),
} = {}) => {
  const { journalPath, migrationsDir } = resolveMigrationPaths(projectRoot);
  const journal = JSON.parse(await readFile(journalPath, "utf8"));
  const entries = [...(journal.entries ?? [])].sort((left, right) => {
    const leftIndex = Number(left.idx ?? 0);
    const rightIndex = Number(right.idx ?? 0);
    return leftIndex - rightIndex;
  });

  return Promise.all(
    entries.map(async (entry) => {
      const filename = `${entry.tag}.sql`;
      const sql = await readFile(path.join(migrationsDir, filename), "utf8");
      return {
        name: filename,
        sql,
      };
    }),
  );
};

/**
 * Generate the TypeScript bundle imported by the Worker at runtime.
 */
export const generateRuntimeMigrationsBundle = async ({
  projectRoot = process.cwd(),
} = {}) => {
  const { outputPath } = resolveMigrationPaths(projectRoot);
  const migrations = await loadRuntimeMigrations({ projectRoot });
  const contents = `import type { RuntimeMigration } from "@nekobato/nabecms";

/**
 * Generated runtime migration bundle from ./migrations and ./migrations/meta/_journal.json.
 * Do not edit this file manually.
 */
export const appRuntimeMigrations: readonly RuntimeMigration[] = ${JSON.stringify(
    migrations,
    null,
    2,
  )};
`;

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, contents, "utf8");
  return outputPath;
};

/**
 * Help text for the bundle-migrations command.
 */
export const formatBundleMigrationsHelp =
  () => `Usage: nabecms bundle-migrations

Regenerates src/database/runtime-migrations.generated.ts from ./migrations and
./migrations/meta/_journal.json in the current working directory.`;

/**
 * Run the bundle-migrations command.
 */
export const runBundleMigrationsCommand = async ({
  projectRoot = process.cwd(),
} = {}) => {
  const generatedPath = await generateRuntimeMigrationsBundle({ projectRoot });
  console.log(`Generated runtime migrations: ${generatedPath}`);
  return 0;
};
